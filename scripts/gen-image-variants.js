const sharp = require('sharp')
const fs = require('fs')
const path = require('path')

// Generates responsive -<w>w.webp variants for every image in the given
// folders and rebuilds src/data/imageVariants.ts. Run this after adding new
// product/blog/video images:  node scripts/gen-image-variants.js

function variantsOf(relDir) {
  const dir = path.join(process.cwd(), 'public', relDir)
  const out = []
  for (const f of fs.readdirSync(dir)) {
    const m = f.match(/^(.*)-(\d+)w\.webp$/)
    if (m) out.push({ base: m[1] + '.webp', w: +m[2] })
  }
  return out
}

function genImageVariants(overrides) {
  const dirs = ['product-images', 'images/blog', 'images/videos']
  const map = {}
  for (const dir of dirs) {
    for (const { base, w } of variantsOf(dir)) {
      if (!map[base]) map[base] = []
      if (!map[base].includes(w)) map[base].push(w)
    }
  }
  for (const [base, ws] of Object.entries(overrides || {})) {
    if (map[base]) map[base] = [...new Set([...map[base], ...ws])].sort((a, b) => a - b)
  }
  const lines = Object.keys(map)
    .sort()
    .map((k) => `  '${k}': [${map[k].join(', ')}],`)
  const ts = `// AUTO-GENERATED by scripts/gen-image-variants.js — do not edit by hand.\nconst IMAGE_VARIANTS: Record<string, number[]> = {\n${lines.join('\n')}\n}\n\nexport default IMAGE_VARIANTS\n`
  fs.writeFileSync(path.join(process.cwd(), 'src/data/imageVariants.ts'), ts, 'utf8')
  console.log('wrote src/data/imageVariants.ts (' + Object.keys(map).length + ' images)')
}

async function makeVariants(relDir, targets) {
  const dir = path.join(process.cwd(), 'public', relDir)
  for (const f of fs.readdirSync(dir)) {
    if (!f.endsWith('.webp') || /-\d+w\.webp$/.test(f)) continue
    const src = path.join(dir, f)
    const meta = await sharp(src).metadata()
    if (!meta.width) continue
    for (const w of targets) {
      if (meta.width <= w) continue
      const out = path.join(dir, f.replace(/\.webp$/, '') + '-' + w + 'w.webp')
      if (fs.existsSync(out)) continue
      await sharp(src)
        .resize({ width: w, withoutEnlargement: true })
        .webp({ quality: 75 })
        .toFile(out)
      console.log('  + ' + path.join(relDir, path.basename(out)) + ' (' + Math.round(fs.statSync(out).size / 1024) + 'KB)')
    }
  }
}

async function main() {
  await makeVariants('product-images', [260, 360, 520, 720]) // 260/520 serve the hero LCP image
  await makeVariants('images/blog', [480, 720])
  await makeVariants('images/videos', [480])
  genImageVariants()
}

main().catch((e) => {
  console.error(e)
  process.exit(1)
})